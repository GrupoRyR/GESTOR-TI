<?php

namespace App\Models;

use Database\Factories\AiSuggestionFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\MorphTo;
use Illuminate\Support\Carbon;

/**
 * An AI suggestion (Stage D6, types/suggestions.ts) about a request
 * (summary, duplicate, criteria, size) or a GitHub release version
 * (release_notes). Child data of its subject: access always goes through
 * the request (company scope + AiRequestPolicy) or the product.
 *
 * Generated by App\Domain\Suggestions\SuggestionGenerator; changed only by
 * App\Domain\Suggestions\Suggestions (accept, discard, regenerate,
 * cancel). Nothing here is ever applied to the subject by itself.
 *
 * @property int $id
 * @property string $subject_type
 * @property int $subject_id
 * @property string $kind summary|duplicate|criteria|size|release_notes
 * @property string $state generating|ready|accepted|discarded|error|cancelled
 * @property ?string $batch
 * @property ?string $provider
 * @property ?string $model
 * @property ?array<string, mixed> $payload
 * @property ?array<string, mixed> $accepted_value
 * @property ?int $accepted_by_id
 * @property ?Carbon $accepted_at
 * @property ?int $discarded_by_id
 * @property ?Carbon $discarded_at
 * @property ?string $discard_reason
 * @property ?array<string, string> $input_hashes
 * @property ?array{message: string, detail: ?string, code: string, at: string} $error
 * @property ?int $ai_interaction_id
 * @property ?int $requested_by_id
 * @property ?Carbon $superseded_at
 * @property Carbon $created_at
 * @property Carbon $updated_at
 */
#[Fillable([
    'subject_type', 'subject_id', 'kind', 'state', 'batch', 'provider', 'model', 'payload', 'accepted_value',
    'accepted_by_id', 'accepted_at', 'discarded_by_id', 'discarded_at', 'discard_reason', 'input_hashes', 'error',
    'ai_interaction_id', 'requested_by_id', 'superseded_at',
])]
class AiSuggestion extends Model
{
    /** @use HasFactory<AiSuggestionFactory> */
    use HasFactory;

    public const KINDS = ['summary', 'duplicate', 'criteria', 'size', 'release_notes'];

    /** Kinds of a request, in the order the batch asks for them. */
    public const REQUEST_KINDS = ['summary', 'criteria', 'size', 'duplicate'];

    public const GENERATING = 'generating';

    public const READY = 'ready';

    public const ACCEPTED = 'accepted';

    public const DISCARDED = 'discarded';

    public const ERROR = 'error';

    public const CANCELLED = 'cancelled';

    protected $attributes = [
        'state' => self::GENERATING,
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'payload' => 'array',
            'accepted_value' => 'array',
            'input_hashes' => 'array',
            'error' => 'array',
            'accepted_at' => 'datetime',
            'discarded_at' => 'datetime',
            'superseded_at' => 'datetime',
        ];
    }

    /**
     * @return MorphTo<Model, $this>
     */
    public function subject(): MorphTo
    {
        return $this->morphTo();
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function acceptedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'accepted_by_id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function discardedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'discarded_by_id');
    }

    /**
     * Suggestions a page may show: not cancelled and not replaced.
     *
     * @param  Builder<AiSuggestion>  $query
     */
    public function scopeCurrent(Builder $query): void
    {
        $query->where('state', '!=', self::CANCELLED)->whereNull('superseded_at');
    }

    /**
     * @param  Builder<AiSuggestion>  $query
     */
    public function scopeOf(Builder $query, Model $subject): void
    {
        $query->where('subject_type', $subject::class)->where('subject_id', $subject->getKey());
    }

    public function isGenerating(): bool
    {
        return $this->state === self::GENERATING;
    }

    /**
     * Ready (or ready but stale): a person may still use or discard it.
     */
    public function isUsable(): bool
    {
        return in_array($this->state, [self::READY, self::ACCEPTED], true) && $this->payload !== null;
    }
}
